// Minimal Service Worker for PWA Installation and Shell Resilience
const CACHE_NAME = 'sarwar-pwa-v1';

self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener('fetch', (event) => {
  // Let the browser handle fetches naturally.
  // Full media caching is handled client-side by our native CacheStorage engine.
  if (event.request.method !== 'GET') return;
  event.respondWith(
    fetch(event.request).catch(() => {
      return caches.match(event.request);
    })
  );
});
